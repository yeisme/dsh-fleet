import { before, describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { SEEDS } from '../scripts/seeds.mjs'
import { assertBundleSane, externalSpecifiers } from '../scripts/build.mjs'
import { build, hasBun, ROOT } from './helpers/bun-build.mjs'
import { permissiveReact, simulateLoader } from './helpers/loader-sim.mjs'

const seedStubs = () => ({
  ...Object.fromEntries(SEEDS.map((spec) => [spec, {}])),
  react: permissiveReact(),
  'react/jsx-runtime': { jsx: (...a) => ({ via: 'jsx', a }), jsxs: (...a) => ({ via: 'jsxs', a }), Fragment: Symbol('Fragment') },
  'react-dom': { createPortal: (...a) => ({ $$: 'portal', a }) },
  '@tanstack/react-virtual': { useVirtualizer: () => ({}) },
})

describe('assertBundleSane', () => {
  it('accepts seed requires and rejects everything else', () => {
    assert.doesNotThrow(() => assertBundleSane('var r = require("react"); var j = __require("react/jsx-runtime")'))
    assert.throws(() => assertBundleSane('var l = require("lodash")'), /non-seed/)
    assert.throws(() => assertBundleSane('import("node:fs")'), /non-seed/)
  })

  it('rejects a bundle that references the JSX dev runtime', () => {
    const devRuntime = ['react', 'jsx-dev-runtime'].join('/')
    assert.throws(() => assertBundleSane(`require("react"); /* ${devRuntime} */`), /development:false/)
    assert.throws(() => assertBundleSane(`require("${devRuntime}")`))
  })
})

describe('build pipeline', { skip: !hasBun && 'bun is not installed' }, () => {
  let real

  before(() => {
    real = build()
    assert.equal(real.status, 0, real.stderr)
  })

  it('emits a classic script in the host factory form that a seed-only loader can run', () => {
    assert.match(real.code, /^\/\* GENERATED by scripts\/build\.mjs/)
    assert.match(real.code, /window\.__ModuleLoader__\.load\(\{id:"@local\/dsh-threads",factory\(require\)\{var module=\{exports:\{\}\};var exports=module\.exports;/)
    const { id, plugin } = simulateLoader(real.code, seedStubs(), { fileName: 'client.js' })
    assert.equal(id, '@local/dsh-threads')
    assert.equal(typeof plugin.apply, 'function')
    assert.deepEqual([...plugin.inject], ['slots', 'locale', 'sessions'])
  })

  it('returns a plain data object (no __esModule marker, no getter exports)', () => {
    const { plugin } = simulateLoader(real.code, seedStubs())
    assert.deepEqual(Object.keys(plugin).sort(), ['apply', 'inject'])
    assert.equal(plugin.__esModule, undefined)
    for (const key of Object.keys(plugin)) assert.equal(typeof Object.getOwnPropertyDescriptor(plugin, key).get, 'undefined', `${key} is a data property`)
  })

  it('requires only host seed words (statically and when the factory runs)', () => {
    const specs = externalSpecifiers(real.code)
    assert.ok(specs.length > 0)
    assert.deepEqual(specs.filter((s) => !SEEDS.includes(s)), [])
    // simulateLoader's require throws on any non-seed specifier, so running the factory proves it dynamically
    simulateLoader(real.code, Object.fromEntries(Object.entries(seedStubs()).filter(([spec]) => SEEDS.includes(spec))))
  })

  it('never references the JSX dev runtime', () => {
    assert.equal(real.code.includes(['react', 'jsx-dev-runtime'].join('/')), false)
  })

  it('is deterministic and independent of the working directory', () => {
    const elsewhere = build([], { cwd: tmpdir() })
    assert.equal(elsewhere.status, 0, elsewhere.stderr)
    assert.equal(elsewhere.code, real.code)
    assert.equal(/\/Users\/|\/private\/|\/var\/folders\//.test(real.code), false, 'no absolute paths leak into the output')
  })

  it('compiles JSX with the automatic runtime against the host seed react/jsx-runtime', () => {
    const fixture = build(['--entry', join(ROOT, 'test/fixtures/build/entry.jsx'), '--no-legacy'])
    assert.equal(fixture.status, 0, fixture.stderr)
    assert.deepEqual(externalSpecifiers(fixture.code), ['@tanstack/react-virtual', 'react', 'react-dom', 'react/jsx-runtime'])
    const { plugin, asked } = simulateLoader(fixture.code, seedStubs())
    const recorded = []
    plugin.apply({ record: (value) => recorded.push(value) })
    assert.equal(recorded[0].hooks, 'function')
    assert.equal(recorded[0].portal, 'function')
    assert.equal(recorded[0].virtual, 'function')
    assert.match(recorded[0].element.via, /^jsxs?$/)
    assert.ok(asked.includes('react/jsx-runtime'))
  })
})
