#!/usr/bin/env bun
/**
 * Build the client bundle: src/main.js (+ the legacy classic fragment) -> ONE classic <script> in the
 * host's factory form:
 *
 *   window.__ModuleLoader__.load({ id, factory(require) { …bundle…; return { inject, apply } } })
 *
 * Usage (needs bun; the Bun.build JS API does the bundling):
 *   bun scripts/build.mjs                  -> dist/client.js      (safe, git-ignored; the default)
 *   bun scripts/build.mjs --out <file>     -> any file
 *   bun scripts/build.mjs --write-client   -> ./client.js         (the LIVE bundle: the host HMR-loads it)
 *   bun scripts/build.mjs --watch …        -> rebuild when src/ changes (rewrites only if bytes changed)
 *   bun scripts/build.mjs --check          -> exit 1 unless ./client.js equals a fresh build
 *   --entry <file>   alternative entry (tests)        --no-legacy   skip the legacy prelude
 *
 * HARD RULES (adopted by the user 2026-11-27; each has an automated guard in test/):
 *  1. JSX is compiled with `development: false`. The module react/jsx-dev-runtime (hard-rule-ignore) is NOT a host
 *     require seed word, so a dev-runtime import would throw "missed the module table" when the host loads us.
 *     Guards: assertBundleSane() below, test/build.test.mjs, test/hard-rules.test.mjs.
 *  2. Only seed words (scripts/seeds.mjs) may remain as `require("…")` in the output; everything else
 *     is bundled in. Guard: assertBundleSane().
 *  3. The output is deterministic: no timestamps, no absolute paths. Guard: test/build.test.mjs.
 *
 * Why the legacy prelude exists: the pre-Fleet client (BTW fork panes, thread tabs, attention shortcut)
 * is kept VERBATIM in src/legacy/threads-btw.classic.js and inlined here as plain text, NOT run through the
 * ESM bundler. That preserves its sloppy-mode semantics and function-scope hoisting exactly (its TDZ
 * workarounds rely on both). It is replaced by real modules after P1, behind the registration-manifest
 * test (test/legacy-manifest.test.mjs).
 */
import { existsSync, mkdirSync, readFileSync, renameSync, watch, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import { SEEDS } from './seeds.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MODULE_ID = '@local/dsh-threads'
const DEFAULT_ENTRY = resolve(ROOT, 'src/main.js')
const LEGACY_FILE = resolve(ROOT, 'src/legacy/threads-btw.classic.js')
const LIVE_CLIENT = resolve(ROOT, 'client.js')
const BANNER = '/* GENERATED by scripts/build.mjs from src/ — DO NOT EDIT. Rebuild: bun run build:client */'

/** Binds the legacy factory to the `require` the host hands to THIS module's factory. */
const LEGACY_GLUE = `
/* glue (scripts/build.mjs): legacy factory bound to this module's host-provided require */
function createLegacyPlugin(){return createLegacy(require)}
`

const rel = (p) => relative(ROOT, p) || '.'

function parseArgs(argv) {
  const args = { entry: DEFAULT_ENTRY, out: resolve(ROOT, 'dist/client.js'), legacy: true, watch: false, check: false, id: MODULE_ID }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    const next = () => {
      if (i + 1 >= argv.length) throw new Error(`${a} needs a value`)
      return argv[++i]
    }
    if (a === '--entry') args.entry = resolve(process.cwd(), next())
    else if (a === '--out') args.out = resolve(process.cwd(), next())
    else if (a === '--write-client') args.out = LIVE_CLIENT
    else if (a === '--no-legacy') args.legacy = false
    else if (a === '--watch') args.watch = true
    else if (a === '--check') args.check = true
    else if (a === '--id') args.id = next()
    else throw new Error(`unknown argument: ${a}`)
  }
  return args
}

async function bundle(entry) {
  const result = await Bun.build({
    entrypoints: [entry],
    root: ROOT, // path comments in the output are relative to the repo, not to the cwd
    target: 'browser',
    format: 'cjs',
    external: [...SEEDS],
    // HARD RULE 1: development:false — see the header of this file.
    jsx: { runtime: 'automatic', importSource: 'react', development: false },
    minify: false,
    sourcemap: 'none',
    splitting: false,
  })
  if (!result.success) throw new Error(`bun build failed:\n${result.logs.map(String).join('\n')}`)
  if (result.outputs.length !== 1) throw new Error(`expected 1 output, got ${result.outputs.length}`)
  return await result.outputs[0].text()
}

/** Every specifier the bundle still requires/imports at run time. */
export function externalSpecifiers(code) {
  const found = new Set()
  for (const m of code.matchAll(/require\w*\(\s*["']([^"']+)["']\s*\)/g)) found.add(m[1])
  for (const m of code.matchAll(/\bimport\s*\(\s*["']([^"']+)["']\s*\)/g)) found.add(m[1])
  return [...found].sort()
}

export function assertBundleSane(code) {
  const outside = externalSpecifiers(code).filter((s) => !SEEDS.includes(s))
  if (outside.length > 0) {
    throw new Error(`bundle requires non-seed specifiers (the host cannot resolve them): ${outside.join(', ')}`)
  }
  if (/jsx-dev-runtime/.test(code)) { // hard-rule-ignore
    throw new Error('bundle references jsx-dev-runtime: JSX must be built with development:false (HARD RULE 1)') // hard-rule-ignore
  }
}

function readLegacy() {
  const text = readFileSync(LEGACY_FILE, 'utf8')
  if (!/^function createLegacy\(require\) \{$/m.test(text)) throw new Error(`${rel(LEGACY_FILE)} must declare "function createLegacy(require) {"`)
  if (/^\s*(import|export)\s/m.test(text)) throw new Error(`${rel(LEGACY_FILE)} is a classic fragment: no import/export statements`)
  return text.endsWith('\n') ? text : `${text}\n`
}

export function wrap({ id, prelude, body }) {
  const tail = body.endsWith('\n') ? '' : '\n'
  return `${BANNER}
window.__ModuleLoader__.load({id:${JSON.stringify(id)},factory(require){var module={exports:{}};var exports=module.exports;
${prelude}${body}${tail}// Plain data properties, exactly what the pre-bundler factory returned (not bun's __esModule/getter object).
return Object.assign({},module.exports)}});
`
}

async function buildCode({ entry, legacy, id }) {
  const body = await bundle(entry)
  assertBundleSane(body)
  const prelude = legacy ? `${readLegacy()}${LEGACY_GLUE}` : ''
  if (legacy && /function createLegacy\b/.test(body)) throw new Error('bundle also defines createLegacy: name clash with the legacy prelude')
  return wrap({ id, prelude, body })
}

const sha8 = (text) => createHash('sha256').update(text).digest('hex').slice(0, 8)

async function buildOnce(args) {
  const code = await buildCode(args)
  if (args.check) {
    const live = existsSync(LIVE_CLIENT) ? readFileSync(LIVE_CLIENT, 'utf8') : null
    if (live === code) {
      console.error(`ok: ${rel(LIVE_CLIENT)} matches a fresh build (${sha8(code)})`)
      return
    }
    console.error(`MISMATCH: ${rel(LIVE_CLIENT)} ${live === null ? 'is missing' : `(${sha8(live)})`} but a fresh build is ${sha8(code)}. Run: bun run build:client`)
    process.exit(1)
  }
  const previous = existsSync(args.out) ? readFileSync(args.out, 'utf8') : null
  if (previous === code) {
    console.error(`unchanged ${rel(args.out)} (${sha8(code)})`)
    return
  }
  mkdirSync(dirname(args.out), { recursive: true })
  // Atomic replace: the host's HMR polls the live bundle (~every 500ms) and must never observe a truncated,
  // half-written script, so write a sibling file and rename it over the target.
  const staging = `${args.out}.tmp-${process.pid}`
  writeFileSync(staging, code)
  renameSync(staging, args.out)
  const live = args.out === LIVE_CLIENT ? '  [LIVE client.js: host HMR will hot-swap it]' : ''
  console.error(`built ${rel(args.out)}  ${Buffer.byteLength(code)} bytes  sha ${sha8(code)}  requires: ${externalSpecifiers(code).join(', ') || '(none)'}${live}`)
}

async function main() {
  const args = parseArgs(process.argv.slice(2)) // paths are resolved against the caller's cwd here …
  // … and only then do we pin the cwd: bun writes `// path/to/file.js` comments relative to the cwd (the `root`
  // option does not affect them), so building from another directory would leak absolute paths and break
  // determinism (test/build.test.mjs).
  process.chdir(ROOT)
  if (args.check && args.watch) throw new Error('--check and --watch are mutually exclusive')
  if (!args.watch) {
    await buildOnce(args)
    return
  }
  const run = async () => {
    try {
      await buildOnce(args)
    } catch (error) {
      console.error(`build error: ${error instanceof Error ? error.message : error}`)
    }
  }
  await run()
  let timer
  watch(resolve(ROOT, 'src'), { recursive: true }, () => {
    clearTimeout(timer)
    timer = setTimeout(run, 80)
  })
  console.error(`watching ${rel(resolve(ROOT, 'src'))}/ …`)
}

if (import.meta.main) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  })
}
